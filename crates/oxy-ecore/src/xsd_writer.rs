//! Generating XML Schemas (XSD) for XMI instance models, so generic XML tooling (such as
//! the LemMinX language server behind VS Code's XML extension) can validate and complete
//! hand-written XMI files structurally.
//!
//! Every package with its own nsURI gets its own schema ([`write_schema`]); schemas of other
//! packages and the XMI schema ([`XMI_SCHEMA`]) are imported by file name
//! ([`schema_file_name`], [`XMI_SCHEMA_FILE`]), so all files belong in one directory.
//!
//! The mapping follows EMF's XMI serialization:
//!
//! * root objects are qualified elements (`<lib:Library>`, one global element per concrete
//!   class); child elements and attributes are unqualified;
//! * each `EClass` becomes a complex type (abstract for abstract classes and interfaces)
//!   whose content is an unbounded choice, so the order of child elements is not enforced
//!   (multiplicities are not enforced either: the OCL engine reports them itself);
//! * containment references are child elements typed by the referenced class (`xsi:type`
//!   selects subclasses); non-containment references are attributes holding URI fragments
//!   or ids, or child elements with `href` for cross-document references;
//! * single-valued attributes are XML attributes, many-valued attributes child elements;
//! * derived and transient features and container references are left out (volatile ones
//!   are kept unless they are transient, as EMF serializes them).
//!
//! Limitations of XSD 1.0:
//!
//! * A type has one base type. A class with several supertypes extends the first one (outside
//!   the Ecore package) and copies the features of the others, so `xsi:type` naming a class
//!   that conforms to the declared type only through a non-first supertype is rejected.
//! * A derived type's content is its base content followed by its own, so child elements of
//!   inherited features must precede those of the class's own features (EMF writes them in
//!   that order); within each group the order is free.
//! * Classes of the Ecore package itself are not described: references typed by them accept
//!   any content (`xsd:anyType`), and features inherited from Ecore classes are copied.

use std::collections::HashSet;
use std::fmt::Write as _;

use indexmap::IndexMap;

use crate::metamodel::*;
use crate::xml::{XMI_NS, escape_attr, escape_text};

/// The file name under which [`XMI_SCHEMA`] is imported by the generated schemas.
pub const XMI_SCHEMA_FILE: &str = "XMI.xsd";

/// A minimal schema for the XMI namespace as EMF uses it: the object attributes
/// (`xmi:id`, `xmi:version`, `xmi:uuid`, `xmi:type`, ...), the `xmi:XMI` wrapper for
/// documents with several root objects and `xmi:Extension` with arbitrary content.
pub const XMI_SCHEMA: &str = r###"<?xml version="1.0" encoding="UTF-8"?>
<!-- XMI 2.0 as written by EMF. Generated by Oxychloride. -->
<xsd:schema xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xmi="http://www.omg.org/XMI"
    targetNamespace="http://www.omg.org/XMI" elementFormDefault="qualified" attributeFormDefault="unqualified">
  <xsd:attribute name="id" type="xsd:string"/>
  <xsd:attribute name="uuid" type="xsd:string"/>
  <xsd:attribute name="label" type="xsd:string"/>
  <xsd:attribute name="idref" type="xsd:string"/>
  <xsd:attribute name="version" type="xsd:string"/>
  <xsd:attribute name="type" type="xsd:QName"/>
  <xsd:attributeGroup name="IdentityAttribs">
    <xsd:attribute ref="xmi:label"/>
    <xsd:attribute ref="xmi:uuid"/>
  </xsd:attributeGroup>
  <xsd:attributeGroup name="LinkAttribs">
    <xsd:attribute name="href" type="xsd:string"/>
    <xsd:attribute ref="xmi:idref"/>
  </xsd:attributeGroup>
  <xsd:attributeGroup name="ObjectAttribs">
    <xsd:attribute ref="xmi:id"/>
    <xsd:attributeGroup ref="xmi:IdentityAttribs"/>
    <xsd:attributeGroup ref="xmi:LinkAttribs"/>
    <xsd:attribute ref="xmi:version"/>
    <xsd:attribute ref="xmi:type"/>
  </xsd:attributeGroup>
  <xsd:complexType name="Any" mixed="true">
    <xsd:sequence>
      <xsd:any minOccurs="0" maxOccurs="unbounded" namespace="##any" processContents="lax"/>
    </xsd:sequence>
    <xsd:anyAttribute namespace="##any" processContents="lax"/>
  </xsd:complexType>
  <xsd:element name="Extension" type="xmi:Any"/>
  <xsd:element name="Documentation" type="xmi:Any"/>
  <xsd:element name="XMI">
    <xsd:complexType>
      <xsd:choice minOccurs="0" maxOccurs="unbounded">
        <xsd:element ref="xmi:Documentation"/>
        <xsd:element ref="xmi:Extension"/>
        <xsd:any namespace="##other" processContents="strict"/>
      </xsd:choice>
      <xsd:attributeGroup ref="xmi:ObjectAttribs"/>
    </xsd:complexType>
  </xsd:element>
</xsd:schema>
"###;

const XSD_NS: &str = "http://www.w3.org/2001/XMLSchema";
const GENMODEL_ANNOTATION_SOURCE: &str = "http://www.eclipse.org/emf/2002/GenModel";
/// Attribute names already declared by `xmi:ObjectAttribs` (unqualified); features with
/// these names are covered by that declaration.
const RESERVED_ATTRIBUTES: &[&str] = &["href"];

/// A stable, file-system-safe file name for the schema of a package, derived from its
/// qualified name (`university.xsd`, `pkg.sub.xsd`). Packages sharing a qualified name get a
/// numeric suffix by load order.
pub fn schema_file_name(mm: &Metamodel, package: PackageId) -> String {
    let base = file_base(mm, package);
    let same = mm.package_ids().filter(|p| *p < package && file_base(mm, *p) == base).count();
    if same == 0 { format!("{base}.xsd") } else { format!("{base}-{}.xsd", same + 1) }
}

fn file_base(mm: &Metamodel, package: PackageId) -> String {
    let mut base: String = mm
        .package_qualified_name(package)
        .replace("::", ".")
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_') { c } else { '_' })
        .collect();
    let base_lower = base.to_ascii_lowercase();
    if base.is_empty() || base.starts_with('.') || base_lower == "xmi" {
        base.insert(0, '_');
    }
    base
}

/// The XSD for the classes and enumerations of one package (not its subpackages).
pub fn write_schema(mm: &Metamodel, package: PackageId) -> String {
    let pkg = mm.package(package);
    let tns = ncname_prefix(if pkg.ns_prefix.is_empty() { &pkg.name } else { &pkg.ns_prefix });
    let mut w = Writer { mm, package, imports: Vec::new(), used_prefixes: vec![tns.clone()] };
    w.used_prefixes.extend(["xsd", "xmi", "xsi"].map(String::from));

    let mut body = String::new();
    for &c in &pkg.classifiers {
        match &mm.classifier(c).kind {
            ClassifierKind::Class(_) => w.class_type_def(&mut body, c),
            ClassifierKind::Enum(literals) => w.enum_type(&mut body, c, literals),
            ClassifierKind::DataType(_) => {}
        }
    }
    for &c in &pkg.classifiers {
        if let Some(data) = mm.class_data(c)
            && !data.is_abstract
            && !data.is_interface
        {
            let name = &mm.classifier(c).name;
            let ty = w.qname(package, name);
            let _ = writeln!(body, "  <xsd:element name=\"{}\" type=\"{}\"/>", escape_attr(name), escape_attr(&ty));
        }
    }

    let mut out = String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
    let _ = writeln!(
        out,
        "<!-- XMI schema for package {} ({}). Generated by Oxychloride; do not edit. -->",
        escape_text(&mm.package_qualified_name(package)).replace("--", "- -"),
        escape_text(&pkg.ns_uri).replace("--", "- -")
    );
    let _ = write!(out, "<xsd:schema xmlns:xsd=\"{XSD_NS}\" xmlns:xmi=\"{XMI_NS}\"");
    if !pkg.ns_uri.is_empty() {
        let _ = write!(out, " xmlns:{tns}=\"{}\"", escape_attr(&pkg.ns_uri));
    }
    for (p, prefix) in w.imports.iter().filter(|(_, prefix)| !prefix.is_empty()) {
        let _ = write!(out, " xmlns:{prefix}=\"{}\"", escape_attr(&mm.package(*p).ns_uri));
    }
    out.push_str("\n   ");
    if !pkg.ns_uri.is_empty() {
        let _ = write!(out, " targetNamespace=\"{}\"", escape_attr(&pkg.ns_uri));
    }
    out.push_str(" elementFormDefault=\"unqualified\" attributeFormDefault=\"unqualified\">\n");
    let _ = writeln!(out, "  <xsd:import namespace=\"{XMI_NS}\" schemaLocation=\"{XMI_SCHEMA_FILE}\"/>");
    for (p, _) in &w.imports {
        let ns = &mm.package(*p).ns_uri;
        let ns = if ns.is_empty() { String::new() } else { format!(" namespace=\"{}\"", escape_attr(ns)) };
        let location = escape_attr(&schema_file_name(mm, *p));
        let _ = writeln!(out, "  <xsd:import{ns} schemaLocation=\"{location}\"/>");
    }
    out.push_str(&body);
    out.push_str("</xsd:schema>\n");
    out
}

/// A valid namespace prefix (NCName, not starting with `xml`) derived from `name`.
fn ncname_prefix(name: &str) -> String {
    let mut s: String =
        name.chars().map(|c| if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') { c } else { '_' }).collect();
    if !s.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_') {
        s.insert(0, '_');
    }
    if s.to_ascii_lowercase().starts_with("xml") {
        s.insert(0, '_');
    }
    s
}

/// The XSD built-in type for values of a data type.
fn builtin_type(kind: DataTypeKind, instance_class: Option<&str>) -> &'static str {
    match kind {
        DataTypeKind::Boolean => "xsd:boolean",
        DataTypeKind::Integer => match instance_class.unwrap_or("") {
            "int" | "java.lang.Integer" => "xsd:int",
            "long" | "java.lang.Long" => "xsd:long",
            "short" | "java.lang.Short" => "xsd:short",
            "byte" | "java.lang.Byte" => "xsd:byte",
            _ => "xsd:integer",
        },
        DataTypeKind::Real => match instance_class.unwrap_or("") {
            "float" | "java.lang.Float" => "xsd:float",
            _ => "xsd:double",
        },
        DataTypeKind::String | DataTypeKind::Other => "xsd:string",
    }
}

fn documentation(annotations: &[Annotation]) -> Option<&str> {
    annotations.iter().find(|a| a.source == GENMODEL_ANNOTATION_SOURCE).and_then(|a| a.detail("documentation"))
}

fn write_documentation(out: &mut String, annotations: &[Annotation], depth: usize) {
    if let Some(doc) = documentation(annotations) {
        let pad = "  ".repeat(depth);
        let _ = writeln!(
            out,
            "{pad}<xsd:annotation><xsd:documentation>{}</xsd:documentation></xsd:annotation>",
            escape_text(doc)
        );
    }
}

/// Appends `<xsd:element name=".." type=".."/>` (or an attribute), with documentation.
fn declaration(out: &mut String, depth: usize, kind: &str, name: &str, ty: &str, doc: Option<&str>) {
    let pad = "  ".repeat(depth);
    let _ = write!(out, "{pad}<xsd:{kind} name=\"{}\" type=\"{}\"", escape_attr(name), escape_attr(ty));
    match doc {
        None => out.push_str("/>\n"),
        Some(doc) => {
            let _ = writeln!(
                out,
                ">\n{pad}  <xsd:annotation><xsd:documentation>{}</xsd:documentation></xsd:annotation>\n{pad}</xsd:{kind}>",
                escape_text(doc)
            );
        }
    }
}

/// Whether a feature appears in XMI files at all. Volatile features are serialized unless
/// they are also transient (EMF writes e.g. `eType` and `instanceClassName` of `.ecore` files).
fn is_serialized(mm: &Metamodel, f: FeatureId) -> bool {
    let feature = mm.feature(f);
    if feature.derived || feature.transient {
        return false;
    }
    // Container references are implied by the containment.
    !feature.opposite().is_some_and(|o| mm.feature(o).is_containment())
}

struct Writer<'a> {
    mm: &'a Metamodel,
    package: PackageId,
    /// Imported packages with the prefixes declared for them.
    imports: Vec<(PackageId, String)>,
    used_prefixes: Vec<String>,
}

impl Writer<'_> {
    /// `prefix:name` for a type or element of `package`, importing it if necessary.
    fn qname(&mut self, package: PackageId, name: &str) -> String {
        let ns = &self.mm.package(package).ns_uri;
        if *ns == self.mm.package(self.package).ns_uri {
            return if ns.is_empty() { name.to_string() } else { format!("{}:{name}", self.used_prefixes[0]) };
        }
        // Packages without nsURI are imported without a namespace; their names stay unprefixed
        // (no default namespace is declared).
        let package = if ns.is_empty() { package } else { self.mm.package_by_ns_uri(ns).unwrap_or(package) };
        if let Some((_, prefix)) = self.imports.iter().find(|(p, _)| *p == package) {
            return if prefix.is_empty() { name.to_string() } else { format!("{prefix}:{name}") };
        }
        if ns.is_empty() {
            self.imports.push((package, String::new()));
            return name.to_string();
        }
        let pkg = self.mm.package(package);
        let base = ncname_prefix(if pkg.ns_prefix.is_empty() { &pkg.name } else { &pkg.ns_prefix });
        let mut prefix = base.clone();
        let mut n = 1;
        while self.used_prefixes.contains(&prefix) {
            prefix = format!("{base}{n}");
            n += 1;
        }
        self.used_prefixes.push(prefix.clone());
        self.imports.push((package, prefix.clone()));
        format!("{prefix}:{name}")
    }

    /// Whether `c` belongs to the Ecore package while another package is written: such
    /// classifiers are not imported (see the module documentation).
    fn is_foreign_ecore(&self, c: ClassifierId) -> bool {
        let ecore = self.mm.ecore_package();
        self.mm.classifier(c).package == ecore && self.package != ecore
    }

    /// The XSD type of objects of a class (for elements of references).
    fn class_type(&mut self, ty: Option<ClassifierId>) -> String {
        match ty {
            Some(c) if self.mm.is_class(c) && !self.is_foreign_ecore(c) => {
                let cl = self.mm.classifier(c);
                self.qname(cl.package, &cl.name)
            }
            _ => "xsd:anyType".to_string(),
        }
    }

    /// The XSD type of values of a data type or enumeration.
    fn value_type(&mut self, ty: Option<ClassifierId>) -> String {
        let Some(c) = ty else { return "xsd:string".to_string() };
        let cl = self.mm.classifier(c);
        match &cl.kind {
            ClassifierKind::Enum(_) if !self.is_foreign_ecore(c) => self.qname(cl.package, &cl.name),
            ClassifierKind::DataType(kind) => builtin_type(*kind, cl.instance_class_name.as_deref()).to_string(),
            _ => "xsd:string".to_string(),
        }
    }

    fn enum_type(&mut self, out: &mut String, c: ClassifierId, literals: &[EnumLiteral]) {
        let cl = self.mm.classifier(c);
        let _ = writeln!(out, "  <xsd:simpleType name=\"{}\">", escape_attr(&cl.name));
        write_documentation(out, &cl.annotations, 2);
        out.push_str("    <xsd:restriction base=\"xsd:string\">\n");
        // The loader accepts a literal's name as well as its literal string.
        let mut seen = HashSet::new();
        for l in literals {
            for value in [&l.literal, &l.name] {
                if seen.insert(value.as_str()) {
                    let _ = writeln!(out, "      <xsd:enumeration value=\"{}\"/>", escape_attr(value));
                }
            }
        }
        out.push_str("    </xsd:restriction>\n  </xsd:simpleType>\n");
    }

    /// The serialized features of a class by name (the most specific feature wins).
    fn serialized_features(&self, class: ClassifierId) -> IndexMap<&str, FeatureId> {
        let mut map = IndexMap::new();
        for &f in self.mm.all_features(class) {
            if is_serialized(self.mm, f) {
                map.insert(self.mm.feature(f).name.as_str(), f);
            }
        }
        map
    }

    fn class_type_def(&mut self, out: &mut String, c: ClassifierId) {
        let mm = self.mm;
        let cl = mm.classifier(c);
        let Some(data) = mm.class_data(c) else { return };
        // The base type: the first supertype outside Ecore (unless the hierarchy is cyclic).
        let base =
            data.super_types.iter().copied().find(|s| {
                mm.is_class(*s) && !self.is_foreign_ecore(*s) && *s != c && !mm.all_super_types(*s).contains(&c)
            });
        let inherited = base.map(|b| self.serialized_features(b)).unwrap_or_default();
        let features: Vec<FeatureId> = self
            .serialized_features(c)
            .into_iter()
            .filter(|(n, _)| !inherited.contains_key(n))
            .map(|(_, f)| f)
            .collect();

        let mut elements = String::new();
        let mut attributes = String::new();
        let attr_depth = if base.is_some() { 4 } else { 2 };
        for f in features {
            let feature = mm.feature(f);
            let doc = documentation(&feature.annotations);
            let reserved = RESERVED_ATTRIBUTES.contains(&feature.name.as_str());
            if feature.is_reference() {
                let ty = self.class_type(feature.ty);
                declaration(&mut elements, attr_depth + 1, "element", &feature.name, &ty, doc);
                if !feature.is_containment() && !reserved {
                    declaration(&mut attributes, attr_depth, "attribute", &feature.name, "xsd:string", doc);
                }
            } else {
                let ty = self.value_type(feature.ty);
                if feature.is_many() {
                    declaration(&mut elements, attr_depth + 1, "element", &feature.name, &ty, doc);
                } else if !reserved {
                    declaration(&mut attributes, attr_depth, "attribute", &feature.name, &ty, doc);
                }
            }
        }

        // Content: the choice of child elements, then the attributes.
        let pad = "  ".repeat(attr_depth);
        let mut content = String::new();
        // `xmi:Extension` only in the root of a hierarchy: a second occurrence in a derived
        // type's choice would make the content model ambiguous.
        if !elements.is_empty() || base.is_none() {
            let _ = writeln!(content, "{pad}<xsd:choice minOccurs=\"0\" maxOccurs=\"unbounded\">");
            content.push_str(&elements);
            if base.is_none() {
                let _ = writeln!(content, "{pad}  <xsd:element ref=\"xmi:Extension\"/>");
            }
            let _ = writeln!(content, "{pad}</xsd:choice>");
        }
        content.push_str(&attributes);
        if base.is_none() {
            let _ = writeln!(content, "{pad}<xsd:attributeGroup ref=\"xmi:ObjectAttribs\"/>");
        }

        let abstract_attr = if data.is_abstract || data.is_interface { " abstract=\"true\"" } else { "" };
        let _ = writeln!(out, "  <xsd:complexType name=\"{}\"{abstract_attr}>", escape_attr(&cl.name));
        write_documentation(out, &cl.annotations, 2);
        match base {
            Some(b) => {
                let base_type = escape_attr(&self.class_type(Some(b)));
                out.push_str("    <xsd:complexContent>\n");
                if content.is_empty() {
                    let _ = writeln!(out, "      <xsd:extension base=\"{base_type}\"/>");
                } else {
                    let _ = writeln!(out, "      <xsd:extension base=\"{base_type}\">");
                    out.push_str(&content);
                    out.push_str("      </xsd:extension>\n");
                }
                out.push_str("    </xsd:complexContent>\n");
            }
            None => out.push_str(&content),
        }
        out.push_str("  </xsd:complexType>\n");
    }
}
